"""Turn the twister output of scripts/test.sh into the evidence of the article.

    python scripts/evidence.py [twister-out] [--size arm-zephyr-eabi-size]

Writes evidence/results.json (machine-readable) and evidence/results.md (the
tables quoted by the article). Every number in the article comes from here.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import re
import shutil
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent.parent
LIBRARY_OBJECTS = ("baton_protocol", "baton_link", "baton_queue", "baton_node")

NOISE = re.compile(r"corrupted bytes: (\d+), CRC errors: (\d+), events lost: (\d+) of (\d+)")
HEAVY = re.compile(
    r"master->0x11: (\d+) delivered, (\d+) reported lost; "
    r"0x11->master: (\d+) delivered, (\d+) reported lost \(of (\d+) each\)"
)


def find_size_tool(given: str | None) -> str | None:
    if given:
        return given
    for name in ("arm-zephyr-eabi-size",):
        path = shutil.which(name)
        if path:
            return path
    for candidate in pathlib.Path("/opt").glob("zephyr-sdk*/gnu/arm-zephyr-eabi/bin/arm-zephyr-eabi-size"):
        return str(candidate)
    return None


def bus_results(out: pathlib.Path, report: dict) -> list[dict]:
    rows = []
    for suite in report["testsuites"]:
        if not suite["name"].startswith("baton.bus"):
            continue
        logs = list(out.glob(f"**/{suite['name']}/handler.log"))
        text = logs[0].read_text(errors="replace") if logs else ""
        cases = suite.get("testcases", [])
        row = {
            "scenario": suite["name"],
            "platform": suite["platform"],
            "status": suite["status"],
            "passed": sum(1 for c in cases if c["status"] == "passed"),
            "cases": len(cases),
        }
        if m := NOISE.search(text):
            row.update(noise_corrupted=int(m[1]), noise_crc_errors=int(m[2]),
                       noise_lost=int(m[3]), noise_sent=int(m[4]))
        if m := HEAVY.search(text):
            row.update(heavy_down_delivered=int(m[1]), heavy_down_reported=int(m[2]),
                       heavy_up_delivered=int(m[3]), heavy_up_reported=int(m[4]),
                       heavy_sent=int(m[5]))
        rows.append(row)
    return rows


def memory(out: pathlib.Path, size_tool: str | None) -> dict:
    result: dict = {}
    libs = list(out.glob("m2s010*/**/sample.baton.node/modules/baton-c/libbaton.a"))
    elfs = list(out.glob("m2s010*/**/sample.baton.node/zephyr/zephyr.elf"))
    if not (libs and elfs and size_tool):
        return result
    lines = subprocess.run([size_tool, libs[0]], capture_output=True, text=True,
                           check=True).stdout.splitlines()[1:]
    library = glue = 0
    for line in lines:
        fields = line.split()
        text, data, name = fields[0], fields[1], fields[5]  # object name, not the archive path
        if any(obj in name for obj in LIBRARY_OBJECTS):
            library += int(text) + int(data)
        elif "baton_zephyr" in name:
            glue += int(text) + int(data)
    result["library_code"] = library
    result["glue_code"] = glue
    nm = size_tool.replace("-size", "-nm")
    symbols = subprocess.run([nm, "-S", elfs[0]], capture_output=True, text=True,
                             check=True).stdout.splitlines()
    for line in symbols:
        parts = line.split()
        if len(parts) == 4 and parts[3] == "baton_data_0":
            result["node_ram"] = int(parts[1], 16)
        if len(parts) == 4 and parts[3] == "baton_stack_0":
            result["thread_stack"] = int(parts[1], 16)
    total = subprocess.run([size_tool, elfs[0]], capture_output=True, text=True,
                           check=True).stdout.splitlines()[1].split()
    result["image_text"], result["image_data"], result["image_bss"] = map(int, total[:3])
    return result


def markdown(env: dict, bus: list[dict], mem: dict) -> str:
    out = ["# Results", "",
           f"Generated by `scripts/evidence.py` from the twister run of {env.get('run_date', '?')}"
           f" (Zephyr {env.get('zephyr_version', '?')}, {env.get('toolchain', '?')}).", "",
           "## Bus test on native_sim", "",
           "| Scenario | Test cases | Moderate noise: corrupted bytes / CRC errors / events lost | "
           "Heavy noise: delivered + reported lost (of 100), master→slave | slave→master |",
           "| --- | --- | --- | --- | --- |"]
    for r in bus:
        moderate = (f"{r['noise_corrupted']} / {r['noise_crc_errors']} / "
                    f"{r['noise_lost']} of {r['noise_sent']}") if "noise_sent" in r else "—"
        down = (f"{r['heavy_down_delivered']} + {r['heavy_down_reported']}"
                if "heavy_sent" in r else "—")
        up = (f"{r['heavy_up_delivered']} + {r['heavy_up_reported']}"
              if "heavy_sent" in r else "—")
        out.append(f"| `{r['scenario']}` | {r['passed']}/{r['cases']} | {moderate} | {down} | {up} |")
    if mem:
        out += ["", "## Memory on the M2S010 MKR Kit (Cortex-M3, -Os)", "",
                "| Item | Bytes |", "| --- | --- |",
                f"| Library code (`src/`) | {mem['library_code']} |",
                f"| Zephyr glue (`baton_zephyr.c`) | {mem['glue_code']} |",
                f"| Node state (`struct baton_zephyr_data`) | {mem.get('node_ram', '?')} |",
                f"| Protocol thread stack | {mem.get('thread_stack', '?')} |",
                f"| Whole sample image: text / data / bss | {mem['image_text']} / "
                f"{mem['image_data']} / {mem['image_bss']} |"]
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("twister_out", nargs="?", default=None)
    parser.add_argument("--size", default=None, help="arm-zephyr-eabi-size to use")
    args = parser.parse_args()

    out = pathlib.Path(args.twister_out) if args.twister_out else HERE.parent / "twister-out"
    report = json.loads((out / "twister.json").read_text())
    bus = bus_results(out, report)
    mem = memory(out, find_size_tool(args.size))
    env = report.get("environment", {})

    evidence = HERE / "evidence"
    evidence.mkdir(exist_ok=True)
    (evidence / "results.json").write_text(
        json.dumps({"environment": env, "bus": bus, "memory": mem}, indent=2) + "\n")
    (evidence / "results.md").write_text(markdown(env, bus, mem))
    shutil.copy(out / "twister_report.xml", evidence / "twister_report.xml")
    print((evidence / "results.md").read_text())
    return 0 if all(r["status"] == "passed" for r in bus) else 1


if __name__ == "__main__":
    sys.exit(main())
